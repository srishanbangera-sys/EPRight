// Pre-purchase Safety Check (Spec 9.5). A single pure function: no DB, no I/O.
// Rule-based screening only; it is not a guarantee.

import { daysBetween } from './fy.js';

export const DEFAULT_THRESHOLDS = {
  price_deviation_pct: 25,
  on_time_min_pct: 80,
  on_time_min_orders: 3,
  doc_expiry_warn_days: 60,
  new_listing_days: 7,
};

const fmt = (n) => Number(n).toLocaleString('en-IN', { maximumFractionDigits: 2 });

/**
 * @param {object} input
 * @param {object} input.listing   {category, tonnes_available, price_per_tonne, expected_completion, created_at}
 * @param {object} input.recycler  {name, status, categories[], documents[{type,valid_to,status}], completedOrders, onTimeRate|null, openDisputes}
 * @param {number} input.remaining producer's remaining tonnes in the listing category for the FY
 * @param {number} input.tonnes    requested tonnes
 * @param {number|null} input.medianPrice median price of active listings in the category
 * @param {string|null} input.filingDeadline YYYY-MM-DD
 * @param {string} input.today     YYYY-MM-DD
 * @param {object} [input.thresholds]
 * @returns {{status:'GREEN'|'AMBER'|'RED', score:number, reasons:Array<{code,severity,text}>, suggestedMax:number}}
 */
export function safetyCheck(input) {
  const { listing, recycler, remaining, tonnes, medianPrice, filingDeadline, today } = input;
  const t = { ...DEFAULT_THRESHOLDS, ...(input.thresholds || {}) };
  const reasons = [];
  const fail = (code, text) => reasons.push({ code, severity: 'FAIL', text });
  const warn = (code, text) => reasons.push({ code, severity: 'WARN', text });
  const info = (code, text) => reasons.push({ code, severity: 'INFO', text });
  const pass = (code, text) => reasons.push({ code, severity: 'PASS', text });

  const docs = recycler.documents || [];
  const verifiedStatus = recycler.status === 'VERIFIED' || recycler.status === 'AT_RISK';
  const expiredDocs = docs.filter((d) => d.status === 'EXPIRED' || (d.valid_to && d.valid_to < today));
  const unapproved = docs.filter((d) => d.status !== 'APPROVED' && d.status !== 'EXPIRED');
  const earliestExpiry = docs.map((d) => d.valid_to).filter(Boolean).sort()[0] || null;

  // ---- Hard failures ----
  if (!verifiedStatus || expiredDocs.length || unapproved.length || !docs.length) {
    const why = !verifiedStatus
      ? `status is ${recycler.status}`
      : expiredDocs.length
        ? `${expiredDocs.map((d) => d.type.replaceAll('_', ' ').toLowerCase()).join(', ')} expired`
        : 'required documents are not approved';
    fail('RECYCLER_NOT_VERIFIED', `Recycler is not verified (${why}). Credits from an unverified recycler may not count.`);
  } else {
    pass('RECYCLER_VERIFIED', `Recycler is verified and all documents are in date (earliest expiry ${earliestExpiry}).`);
  }

  if (earliestExpiry && listing.expected_completion && earliestExpiry < listing.expected_completion && !expiredDocs.length) {
    fail('DOCS_EXPIRE_BEFORE_COMPLETION', `Recycler documents expire on ${earliestExpiry}, before the expected completion date ${listing.expected_completion}. The credit could be generated by a recycler without valid consent.`);
  }

  if (remaining <= 0) {
    fail('NO_REMAINING_OBLIGATION', `You have no remaining obligation in Category ${listing.category} this financial year. Credits only count against the same category, so this purchase would be wasted.`);
  }

  if (!(recycler.categories || []).includes(listing.category)) {
    fail('CATEGORY_NOT_REGISTERED', `Recycler is not registered to process Category ${listing.category} plastic. A credit in this category from them would not be valid.`);
  } else {
    pass('CATEGORY_REGISTERED', `Recycler is registered for Category ${listing.category}.`);
  }

  if (tonnes > listing.tonnes_available) {
    fail('EXCEEDS_AVAILABILITY', `You asked for ${fmt(tonnes)} t but only ${fmt(listing.tonnes_available)} t is available in this listing.`);
  }

  // ---- Warnings ----
  const suggestedMax = Math.max(0, Math.min(remaining, listing.tonnes_available));
  if (remaining > 0 && tonnes > remaining) {
    warn('EXCEEDS_REMAINING', `You asked for ${fmt(tonnes)} t but you only need ${fmt(remaining)} t more in Category ${listing.category}. Suggested maximum: ${fmt(suggestedMax)} t. Extra tonnes become surplus.`);
  }

  if (medianPrice && medianPrice > 0) {
    const dev = ((listing.price_per_tonne - medianPrice) / medianPrice) * 100;
    if (Math.abs(dev) > t.price_deviation_pct) {
      warn('PRICE_DEVIATION', `Price ₹${fmt(listing.price_per_tonne)}/t is ${Math.abs(dev).toFixed(0)}% ${dev > 0 ? 'above' : 'below'} the median ₹${fmt(medianPrice)}/t for Category ${listing.category}. ${dev > 0 ? 'You may be overpaying.' : 'Unusually cheap credits deserve extra scrutiny.'}`);
    } else {
      pass('PRICE_OK', `Price is within ${t.price_deviation_pct}% of the category median (₹${fmt(medianPrice)}/t).`);
    }
  }

  if (recycler.completedOrders >= t.on_time_min_orders && recycler.onTimeRate != null) {
    if (recycler.onTimeRate < t.on_time_min_pct) {
      warn('LOW_ON_TIME', `Recycler delivered on time in only ${recycler.onTimeRate.toFixed(0)}% of ${recycler.completedOrders} completed orders (threshold ${t.on_time_min_pct}%). Your credit may arrive late.`);
    } else {
      pass('ON_TIME_OK', `Recycler delivered on time in ${recycler.onTimeRate.toFixed(0)}% of ${recycler.completedOrders} completed orders.`);
    }
  }

  if (recycler.openDisputes > 0) {
    warn('OPEN_DISPUTES', `Recycler has ${recycler.openDisputes} open dispute(s) with other buyers.`);
  }

  if (filingDeadline && listing.expected_completion && listing.expected_completion > filingDeadline) {
    warn('AFTER_DEADLINE', `Expected completion ${listing.expected_completion} is after your filing deadline ${filingDeadline}. The credit may not arrive in time to count.`);
  }

  if (earliestExpiry && !expiredDocs.length && earliestExpiry >= (listing.expected_completion || today)) {
    const days = daysBetween(today, earliestExpiry);
    if (days <= t.doc_expiry_warn_days) {
      warn('DOCS_EXPIRING_SOON', `Recycler documents expire in ${days} days (${earliestExpiry}). Make sure delivery happens before then.`);
    }
  }

  // ---- Info ----
  if (!recycler.completedOrders) info('NO_HISTORY', 'Recycler has no completed orders on EPRight yet, so there is no delivery track record.');
  if (listing.created_at && daysBetween(listing.created_at.slice(0, 10), today) <= t.new_listing_days) info('NEW_LISTING', 'This listing is new (posted in the last week).');

  const failures = reasons.filter((r) => r.severity === 'FAIL').length;
  const warnings = reasons.filter((r) => r.severity === 'WARN').length;
  const score = Math.max(0, 100 - 40 * failures - 15 * warnings);
  const status = failures ? 'RED' : warnings ? 'AMBER' : 'GREEN';
  const order = { FAIL: 0, WARN: 1, INFO: 2, PASS: 3 };
  reasons.sort((a, b) => order[a.severity] - order[b.severity]);
  return { status, score, reasons, suggestedMax };
}
